// "Download" button: the three financial statements (plus ratios) as Excel or PDF, built in the browser.
// The libraries are only loaded when someone clicks, so the page stays fast.
import { INCOME_ROWS, BALANCE_ROWS, CASHFLOW_ROWS, RATIO_ROWS } from './rows.js';
import { yearlyRatios } from './lib/finance.js';

const loaded = {};
function loadScript(src) {
  loaded[src] ||= new Promise((resolve, reject) => {
    const s = document.createElement('script');
    s.src = src;
    s.onload = resolve;
    s.onerror = () => reject(new Error(`Could not load ${src}`));
    document.head.appendChild(s);
  });
  return loaded[src];
}

const fileBase = (c) => `${c.profile.symbol}_financial_statements_FinancialRat`;
const today = () => new Date().toISOString().slice(0, 10);

/** Only the lines the data source actually reported for at least one year. */
const reported = (company, key, rows) => rows.filter(([field]) => company[key].some((r) => typeof r[field] === 'number'));

function sheetRows(company, key, rows) {
  const data = company[key];
  return reported(company, key, rows).map(([field, label]) => [label, ...data.map((r) => (typeof r[field] === 'number' ? r[field] : null))]);
}

export async function downloadExcel(company) {
  await loadScript('/vendor/xlsx.full.min.js');
  const XLSX = window.XLSX;
  const wb = XLSX.utils.book_new();
  const { profile } = company;
  const header = (title, data) => [
    [`${profile.name} (${profile.symbol}) — ${title}`],
    [`Currency: ${profile.currency}. Values in full units (not millions). Fiscal years.`],
    [`Source: ${company.source}. Generated by Financial Rat (financialrat.com) on ${today()}. For education only — verify with the company's official filings.`],
    ['Empty cells: the data source did not report that line for that year. Lines with no data in any year are left out.'],
    [],
    ['Fiscal year', ...data.map((r) => r.fiscalYear)],
    ['Period end', ...data.map((r) => r.date || '')],
  ];
  const add = (name, title, key, rows) => {
    const aoa = [...header(title, company[key]), ...sheetRows(company, key, rows)];
    const ws = XLSX.utils.aoa_to_sheet(aoa);
    ws['!cols'] = [{ wch: 34 }, ...company[key].map(() => ({ wch: 16 }))];
    const range = XLSX.utils.decode_range(ws['!ref']);
    for (let R = 7; R <= range.e.r; R++) {
      for (let C = 1; C <= range.e.c; C++) {
        const cell = ws[XLSX.utils.encode_cell({ r: R, c: C })];
        if (cell && typeof cell.v === 'number') cell.z = Math.abs(cell.v) < 100 ? '0.00' : '#,##0';
      }
    }
    XLSX.utils.book_append_sheet(wb, ws, name);
  };
  add('Income Statement', 'Income statement', 'income', INCOME_ROWS);
  add('Balance Sheet', 'Balance sheet', 'balance', BALANCE_ROWS);
  add('Cash Flow', 'Cash flow statement', 'cashflow', CASHFLOW_ROWS);

  const ratios = yearlyRatios(company);
  const ratioAoa = [
    [`${profile.name} (${profile.symbol}) — Financial ratios (calculated by Financial Rat)`], [], ['Fiscal year', ...ratios.map((r) => r.fiscalYear)],
    ...RATIO_ROWS.filter((r) => !r.group).map((r) => [r.label, ...ratios.map((y) => (typeof y[r.key] === 'number' ? y[r.key] : null))]),
  ];
  const rws = XLSX.utils.aoa_to_sheet(ratioAoa);
  rws['!cols'] = [{ wch: 30 }, ...ratios.map(() => ({ wch: 10 }))];
  RATIO_ROWS.filter((r) => !r.group).forEach((r, i) => {
    ratios.forEach((_, j) => {
      const cell = rws[XLSX.utils.encode_cell({ r: 3 + i, c: 1 + j })];
      if (cell && typeof cell.v === 'number') cell.z = r.fmt === 'pct' ? '0.0%' : '0.00';
    });
  });
  XLSX.utils.book_append_sheet(wb, rws, 'Ratios');

  const info = XLSX.utils.aoa_to_sheet([
    ['Company', profile.name], ['Ticker', profile.symbol], ['Exchange', profile.exchange], ['Sector', profile.sector], ['Industry', profile.industry],
    ['Currency', profile.currency], ['Price', company.quote?.price ?? ''], ['Market cap', company.quote?.marketCap ?? ''],
    ['Data source', company.source], ['Downloaded', today()], [],
    ['Disclaimer', 'Financial Rat provides this data for education only. It is not investment advice. Data may contain errors; check official filings.'],
  ]);
  info['!cols'] = [{ wch: 16 }, { wch: 90 }];
  XLSX.utils.book_append_sheet(wb, info, 'About');
  XLSX.writeFile(wb, `${fileBase(company)}.xlsx`);
}

export async function downloadPdf(company) {
  await loadScript('/vendor/jspdf.umd.min.js');
  await loadScript('/vendor/jspdf.plugin.autotable.min.js');
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  const { profile } = company;
  const W = doc.internal.pageSize.getWidth();
  const millions = (v) => (typeof v === 'number' ? (v / 1e6).toLocaleString('en-US', { maximumFractionDigits: Math.abs(v) < 1e7 ? 1 : 0 }) : '—');
  const small = (v) => (typeof v === 'number' ? v.toFixed(2) : '—');
  const perShare = new Set(['eps', 'epsDiluted']);

  doc.setFillColor(14, 159, 110);
  doc.rect(0, 0, W, 64, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.text(`${profile.name} (${profile.symbol})`, 36, 30);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`Financial statements · ${profile.currency} millions (per-share items in ${profile.currency}) · Source: ${company.source} · ${today()}`, 36, 50);
  doc.setTextColor(232, 137, 12);
  doc.setFont('helvetica', 'bold');
  doc.text('Financial Rat — Finance For All, All For Finance', W - 36, 30, { align: 'right' });

  let first = true;
  const table = (title, key, rows) => {
    const data = company[key];
    const startY = first ? 92 : doc.lastAutoTable.finalY + 34;
    first = false;
    doc.setTextColor(15, 27, 45);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.text(title, 36, startY - 10);
    doc.autoTable({
      startY,
      head: [['', ...data.map((r) => `FY${r.fiscalYear}`)]],
      body: reported(company, key, rows).map(([field, label]) => [label, ...data.map((r) => (field === 'sharesDiluted' ? millions(r[field]) : perShare.has(field) ? small(r[field]) : millions(r[field])))]),
      styles: { fontSize: 8, cellPadding: 3, halign: 'right' },
      columnStyles: { 0: { halign: 'left', fontStyle: 'bold', cellWidth: 170 } },
      headStyles: { fillColor: [15, 27, 45], halign: 'right' },
      alternateRowStyles: { fillColor: [244, 246, 250] },
      margin: { left: 36, right: 36 },
      pageBreak: 'auto',
    });
  };
  table('Income statement', 'income', INCOME_ROWS);
  table('Balance sheet', 'balance', BALANCE_ROWS);
  table('Cash flow statement', 'cashflow', CASHFLOW_ROWS);

  const pages = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(102, 115, 138);
    doc.text('For education only — not investment advice. Data from third-party providers may contain errors; verify with official company filings.', 36, doc.internal.pageSize.getHeight() - 18);
    doc.text(`Page ${i} of ${pages}`, W - 36, doc.internal.pageSize.getHeight() - 18, { align: 'right' });
  }
  doc.save(`${fileBase(company)}.pdf`);
}
